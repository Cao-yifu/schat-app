  function flat(block) {
    const out = [];
    function walk(v) {
      if (Array.isArray(v)) v.forEach(walk);
      else if (v && typeof v === 'object') Object.keys(v).forEach(function (k) { walk(v[k]); });
      else out.push(v);
    }
    walk(block);
    return out;
  }
